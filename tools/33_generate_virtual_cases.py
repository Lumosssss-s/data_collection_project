def triage_records(idx, terms):
    out = []
    n = 0
    # routine：15 类 × 4 变体 = 60
    for ci, (comp_a, comp_b, dur, detail, flags, dept, scen) in enumerate(NORMAL):
        for vi in range(4):
            n += 1
            age, sex, smoke, extra = VARIANTS[(ci * 2 + vi) % len(VARIANTS)]
            comp = comp_a if vi < 2 else comp_b
            lead = "%s岁%s，%s。%s" % (age, sex, smoke, comp)
            if dur:
                lead += "，持续%s" % dur
            text = "%s。%s。%s。" % (lead, detail, extra)
            out.append(make_triage(n, text, flags, dept, "routine", scen, idx, terms))
    # urgent：15 类 × 2 变体 = 30
    for ci, (comp_a, comp_b, dur, detail, flags, dept, scen) in enumerate(URGENT):
        for vi in range(2):
            n += 1
            age, sex, smoke, extra = VARIANTS[(ci * 3 + vi) % len(VARIANTS)]
            comp = comp_a if vi == 0 else comp_b
            lead = "%s岁%s，%s。%s" % (age, sex, smoke, comp)
            if dur:
                lead += "，持续%s" % dur
            text = "%s。%s。%s。" % (lead, detail, extra)
            out.append(make_triage(n, text, flags, dept, "urgent", scen, idx, terms))
    # emergency：10 条
    for ci, (comp, detail, flags, dept, scen) in enumerate(EMERGENCY):
        n += 1
        age, sex, smoke, extra = VARIANTS[ci % len(VARIANTS)]
        text = "%s岁%s，%s。%s。%s。%s。" % (age, sex, smoke, comp, detail, extra)
        out.append(make_triage(n, text, flags, dept, "emergency", scen, idx, terms))
    return out


def map_flags(flags, terms):
    """原始红旗征 → canonical（A5 有词条则映射），并保留原始表述。"""
    mapped = []
    detail = []
    for raw in flags:
        canonical = FLAG_ALIAS.get(raw)
        term_id, status = terms.get(canonical, (None, None)) if canonical else (None, None)
        mapped.append(canonical or raw)
        detail.append({"raw": raw, "canonical": canonical,
                       "term_id": term_id, "mapping_status": status})
    return mapped, detail


