def load_list(path):
    with open(path, encoding="utf-8") as f:
        d = json.load(f)
    return d if isinstance(d, list) else d.get("records", d)


def rec_index():
    """按 scenario 分组 rec_id，供病例确定性引用。"""
    idx = {}
    for r in load_list(A2):
        idx.setdefault(r.get("scenario"), []).append(r["rec_id"])
    return {k: sorted(v) for k, v in idx.items()}


def pick_rec(idx, scenario, n=2):
    ids = idx.get(scenario) or idx.get("diagnosis") or []
    return ids[:n]


def symptom_index():
    """A5 symptom canonical → (term_id, mapping_status)。"""
    out = {}
    for t in load_list(TERM):
        if t.get("category") == "symptom":
            out[t["canonical"]] = (t["term_id"], t.get("mapping_status"))
    return out


